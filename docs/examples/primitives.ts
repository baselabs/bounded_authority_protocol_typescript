import assert from "node:assert/strict";
import { generateKeyPairSync } from "node:crypto";
import * as bap from "@bounded-authority-protocol/verifier";
const key = Buffer.from(generateKeyPairSync("ed25519").publicKey.export({ format: "jwk" }).x!, "base64url");
const jwk = bap.jwkFromPublicKey(key);
assert.ok(bap.jwkDecodePublic(bap.jwkEncodePublic(key)).ok);
assert.equal(bap.thumbprintRaw(jwk).length, 32);
assert.equal(bap.thumbprintPreimage(jwk).length > 0, true);
assert.equal(bap.publicKeyThumbprintRaw(key).length, 32);
assert.equal(bap.sha256(bap.strUtf8("hello")).length, 32);
assert.equal(bap.utf8Str(bap.base64urlDecode(bap.base64urlEncode(bap.strUtf8("hello")))), "hello");
assert.equal(bap.utf8Str(bap.jcsEncode(bap.jsonDecode(bap.strUtf8('{"b":2,"a":1}')))), '{"a":1,"b":2}');
assert.equal(bap.typedProject({ t: "null" }).t, "array");
assert.ok(bap.semanticIdentity({ t: "int", v: 1 }).length > 0);
assert.equal(bap.boundsMaximum().maximum.digest_bytes, 32);
assert.equal(bap.boundsNew({ json_bytes: 1024 }).overrides.get("json_bytes"), 1024);
assert.deepEqual(bap.ok(7), { ok: true, value: 7 });
assert.deepEqual(bap.err(), { ok: false });
assert.deepEqual(bap.trying(() => bap.fail()), { ok: false });
bap.assert(true);
assert.throws(() => bap.assert(false), bap.InvalidError);
assert.equal(new bap.InvalidError().name, "InvalidError");
